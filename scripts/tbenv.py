def render(v):
    https = lambda h: f"https://{h}"
    be, www, cloud, help_ = https(v["BACKEND_HOST"]), https(v["WEBSITE_HOST"]), https(v["CLOUD_HOST"]), https(v["HELP_HOST"])
    run = {p: https(v[f"APP_{p}_HOST"]) for p in PRODUCTS}
    origins = [run[p] for p in PRODUCTS] + [www, cloud, be]
    origins += [o.strip() for o in v["EXTRA_CORS_ORIGINS"].split(",") if o.strip()]
    cors = list(dict.fromkeys(origins))
    env = {
        "postgres": [("POSTGRES_USER", FIXED["POSTGRES_USER"]), ("POSTGRES_DB", "postgres"),
                     ("STRAPI_DB_NAME", FIXED["STRAPI_DB_NAME"]), ("STRAPI_DB_USER", FIXED["STRAPI_DB_USER"]),
                     ("PGADMIN_DEFAULT_EMAIL", FIXED["PGADMIN_DEFAULT_EMAIL"])],
        "tbbe": [("DATABASE_HOST", "tbpgdb"), ("DATABASE_PORT", "5432"), ("DATABASE_NAME", FIXED["STRAPI_DB_NAME"]),
                 ("DATABASE_USERNAME", FIXED["STRAPI_DB_USER"]), ("DATABASE_SSL", "false"), ("HOST", "0.0.0.0"),
                 ("PORT", "1337"), ("PUBLIC_URL", be), ("CORS_ORIGINS", ",".join(cors)),
                 ("EMAIL_FROM", v["EMAIL_FROM"]), ("EMAIL_REPLY_TO", v["EMAIL_REPLY_TO"] or v["EMAIL_FROM"])],
        "tbwww": [("NEXTAUTH_URL", www), ("CLOUD_API_URL", f"{be}/api"), ("CLOUD_URL", cloud), ("CLOUD_HELP_URL", help_),
                  ("RUN_URL_AB", run["AB"]), ("RUN_URL_TB", run["TB"]), ("RUN_URL_CB", run["CB"]),
                  ("HELP_EDITORS", v["HELP_EDITORS"]), ("TB_ENVIRONMENT", v["ENVIRONMENT"])],
        "tbhelp": [("STRAPI_URL", "http://tbbe:1337/api"), ("NEXTAUTH_URL", cloud), ("CLOUD_API_URL", f"{be}/api"),
                   ("CLOUD_WWW_URL", www), ("CLOUD_HELP_URL", help_), ("RUN_URL_AB", run["AB"]), ("RUN_URL_TB", run["TB"]),
                   ("RUN_URL_CB", run["CB"]), ("HELP_EDITORS", v["HELP_EDITORS"]), ("TB_ENVIRONMENT", v["ENVIRONMENT"])],
    }
    offline = v["APP_OFFLINE"] == "yes"
    sites = [{"host": v[f"APP_{p}_HOST"], "product": p, "offline": offline} for p in PRODUCTS]
    runtime = {"apiUrl": f"{be}/api", "wwwUrl": www, "cloudUrl": cloud, "helpUrl": help_, "opUrl": v["OP_URL"], "aiBaseUrl": "/ai",
               "sites": sites, "productPublicHost": {p: v[f"APP_{p}_HOST"] for p in PRODUCTS}}
    return env, runtime


def routes(v):
    """Every public name: (name, what it is, stack)."""
    rows = [(v[f"APP_{p}_HOST"], label, "tbrun") for (k, _, label), p in zip(NAMES[:3], PRODUCTS)]
    rows += [(v["BACKEND_HOST"], "Strapi backend", "tbbe"), (v["WEBSITE_HOST"], "Website", "tbwww"),
             (v["CLOUD_HOST"], "Timebars Cloud", "tbhelp"), (v["HELP_HOST"], "Help library (Timebars Cloud)", "tbhelp")]
    return rows


def env_text(stack, pairs):
    return "\n".join([f"# {stack}/.env.local - settings of this stack, {GENERATED_NOTE}.",
                      "# Keys and passwords are not here: they are in .secrets.env (from ../secrets.env)."]
                     + [f"{k}={val}" for k, val in pairs]) + "\n"


def runtime_text(rt):
    rows = [f'    {{ "host": {json.dumps(s["host"])}, "product": "{s["product"]}", "offline": {str(s["offline"]).lower()} }}'
            for s in rt["sites"]]
    return "\n".join(["{", f'  "apiUrl": {json.dumps(rt["apiUrl"])},', f'  "wwwUrl": {json.dumps(rt["wwwUrl"])},',
                      f'  "cloudUrl": {json.dumps(rt["cloudUrl"])},', f'  "helpUrl": {json.dumps(rt["helpUrl"])},',
                      f'  "opUrl": {json.dumps(rt["opUrl"])},',
                      f'  "aiBaseUrl": {json.dumps(rt["aiBaseUrl"])},', '  "sites": [', ",\n".join(rows), "  ],",
                      f'  "productPublicHost": {json.dumps(rt["productPublicHost"])}', "}"]) + "\n"


def caddy_text(v):
    prod = v["ENVIRONMENT"] == "PROD"
    t = [f"# proxy/Caddyfile - the {v['ENVIRONMENT']} names and where each one goes. {GENERATED_NOTE}.",
         "# With PROXY=own this file is the route list for your own proxy (see DEPLOY.md)."]
    glob = []
    if v["TLS"] == "internal":
        glob.append("\tlocal_certs                    # TLS=internal: Caddy's own certificate authority, no Let's Encrypt")
    elif v["ACME_EMAIL"]:
        glob.append(f"\temail {v['ACME_EMAIL']}")
    if glob:
        t += ["{"] + glob + ["}"]
    t += ["", "(tb_common) {", "\theader -Server"]
    if not prod:
        t.append('\theader X-Robots-Tag "noindex, nofollow"   # not PROD: keep search engines out')
    t += ["}", ""]
    rows = routes(v)
    apps = [h for h, _, s in rows if s == "tbrun"]
    t += ["# Agilebars, Timebars, Costbars - one app; it picks the product from the name",
          f"{', '.join(apps)} {{", "\timport tb_common", f"\treverse_proxy {TARGETS['tbrun'][0]}", "}", ""]
    for h, what, s in rows:
        if s != "tbrun":
            t += [f"# {what}", f"{h} {{", "\timport tb_common", f"\treverse_proxy {TARGETS[s][0]}", "}", ""]
    return "\n".join(t)


def environment_text(v):
    lines = [f"# environment.env - what this folder is. {GENERATED_NOTE}.",
             f"ENVIRONMENT={v['ENVIRONMENT']}", f"PROXY={v['PROXY']}", f"TLS={v['TLS']}", f"SERVER_IP={v['SERVER_IP']}",
             f"LISTEN_IP={v['LISTEN_IP']}"]
    lines += [f"{k}={v[k]}" for k, _, _ in NAMES]
    return "\n".join(lines) + "\n"


