def write(path, text, mode=0o644):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)
    os.chmod(path, mode)


def copy_tree(src, dst):
    for root, dirs, files in os.walk(src):
        rel = os.path.relpath(root, src)
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for f in files:
            if rel.replace(os.sep, "/").startswith("tbbe/public/uploads") and f != ".gitkeep":
                continue
            shutil.copy2(os.path.join(root, f), os.path.join(dst, rel, f))


def make(v, force):
    env = v["ENVIRONMENT"]
    d = os.path.join(ENVS, env)
    copy_tree(TEMPLATES, d)
    copy_tree(os.path.join(REPO, "seed"), os.path.join(d, "seed"))
    shutil.copy2(os.path.join(REPO, "VERSION.md"), os.path.join(d, "VERSION.md"))
    stacks, rt = render(v)
    for stack, pairs in stacks.items():
        write(os.path.join(d, stack, ".env.local"), env_text(stack, pairs), 0o600)
    write(os.path.join(d, "tbrun", "runtime-config.json"), runtime_text(rt))
    if v["LISTEN_IP"] != "127.0.0.1":  # PROXY=own on another machine: the apps listen where it reaches them
        for stack in TARGETS:
            f = os.path.join(d, stack, "docker-compose.yml")
            text = open(f).read().replace('"127.0.0.1:', f'"{v["LISTEN_IP"]}:')
            write(f, text)
    write(os.path.join(d, "proxy", "Caddyfile"), caddy_text(v))
    write(os.path.join(d, "environment.env"), environment_text(v))
    write(os.path.join(d, "DEPLOY.md"), deploy_md(v))
    sp = os.path.join(d, "secrets.env")
    if not os.path.exists(sp):
        write(sp, tbsecrets.template(env, {k: v[k] for k in KEYS if v[k]}), 0o600)
    for root, _, files in os.walk(d):
        for f in files:
            if f.endswith(".sh"):
                os.chmod(os.path.join(root, f), 0o755)
    return d


def main(argv):
    args = argv[1:]
    check_only = "--check" in args
    force = [a.upper() for a in args if not a.startswith("-")]
    if any(a not in ("--check", "--force") for a in args if a.startswith("-")) or ("--force" in args and not force):
        say(__doc__)
        return 1
    if not os.path.isfile(CONF):
        say(f"No {CONF}. Make it:  cp tbapps.conf.example tbapps.conf   then fill it in and run this again.")
        return 1
    if os.stat(CONF).st_mode & 0o077:
        os.chmod(CONF, 0o600)
    sections, order = read_conf(CONF)
    if not order:
        say("tbapps.conf has no environment section ([DEV], [PROD] ...).")
        return 1
    unknown = [e for e in force if e not in order]
    if unknown:
        say(f"--force {' '.join(unknown)}: no such section in tbapps.conf ({', '.join(order)})")
        return 1
    resolved, bad, seen = {}, False, {}
    for env in order:
        errs, warns, v = resolve(env, sections)
        say(f"[{env}]  {v['APP_TB_HOST'] or '?'} ...  proxy {v['PROXY']}, TLS {v['TLS']}, server {v['SERVER_IP'] or '?'}")
        for w in warns:
            say(f"    note: {w}")
        for e in errs:
            say(f"    FIX:  {e}")
        for k in HOSTS:
            if v[k] in seen and seen[v[k]] != env:
                say(f"    FIX:  {k}={v[k]} is also a name of [{seen[v[k]]}] - each environment needs its own names")
                bad = True
            seen.setdefault(v[k], env)
        bad = bad or bool(errs)
        resolved[env] = v
    if bad:
        say("\nFix the lines marked FIX in tbapps.conf, then run this again. Nothing was written.")
        return 1
    say("")
    made = 0
    for env, v in resolved.items():
        d = os.path.join(ENVS, env)
        exists = os.path.isdir(d)
        if exists and env not in force:
            say(f"  envs/{env}  exists - kept (edit its files, or: bash scripts/apply.sh --force {env})")
            continue
        if check_only:
            say(f"  envs/{env}  would be {'made again' if exists else 'made'}")
            continue
        make(v, env in force)
        made += 1
        say(f"  envs/{env}  {'made again (secrets.env and the running state kept)' if exists else 'made'}")
    if check_only:
        say("\n(check only: nothing written)")
    elif made:
        say("\nNext: open envs/<ENV>/DEPLOY.md - the names for your DNS team, the routes for your own proxy, and the steps.")
    return 0


