#!/usr/bin/env python3
"""tbenv.py — turn tbapps.conf into one ready-to-deploy folder per environment (envs/DEV, envs/PROD ...).

Run it through scripts/apply.sh, on the dev box, in your clone of tbown:
  bash scripts/apply.sh                 make the folders of the environments that do not have one yet
  bash scripts/apply.sh --check         check tbapps.conf and show what would be made; writes nothing
  bash scripts/apply.sh --force PROD    make envs/PROD again from tbapps.conf (after a big change). Keeps
                                        what belongs to the running environment: secrets.env, each stack's
                                        .secrets.env and .env, uploaded files. Your hand edits in the
                                        generated files are replaced.

Each envs/<ENV> folder is the package for that environment's server: the stack folders with their settings
(.env.local, runtime-config.json, Caddyfile), secrets.env (keys; passwords are made on the server), the
seed data, the numbered scripts, deploy-all.sh, 00-push-to-server.sh, and DEPLOY.md (its names for the DNS
team, the routes for your own proxy, and the steps). Open and check them in VS Code; small changes (find
and replace) need no new apply.
"""
