PRODUCTS = ("AB", "TB", "CB")
NAMES = [("APP_AB_HOST", "agile", "Agilebars"), ("APP_TB_HOST", "pmrm", "Timebars"), ("APP_CB_HOST", "ppm", "Costbars"),
         ("BACKEND_HOST", "be2", "Strapi backend"), ("WEBSITE_HOST", "www", "Website"), ("CLOUD_HOST", "cloud", "Timebars Cloud"),
         ("HELP_HOST", "help", "Help library")]
HOSTS = [k for k, _, _ in NAMES]
SETTINGS = ["ACME_EMAIL", "EMAIL_FROM", "EMAIL_REPLY_TO", "APP_OFFLINE", "EXTRA_CORS_ORIGINS", "OP_URL", "HELP_EDITORS",
            "SERVER_IP", "PROXY", "TLS", "LISTEN_IP"] + HOSTS
KEYS = [k for k, _ in tbsecrets.KEYS]
FIXED = {"POSTGRES_USER": "pgsuper", "STRAPI_DB_NAME": "strapi", "STRAPI_DB_USER": "strapi",
         "PGADMIN_DEFAULT_EMAIL": "admin@example.com"}
# Where each container listens: (container:port on tbnet, the same on this machine only)
TARGETS = {"tbrun": ("tbrun:80", "127.0.0.1:8687"), "tbbe": ("tbbe:1337", "127.0.0.1:1337"),
           "tbwww": ("tbwwwp:3001", "127.0.0.1:3001"), "tbhelp": ("tbhelpapp:3010", "127.0.0.1:3010")}
# Files apply makes again with --force; everything else in the folder belongs to the running environment
GENERATED_NOTE = "GENERATED by scripts/apply.sh from tbapps.conf on the dev box"

HOST_RE = re.compile(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$")
IP_RE = re.compile(r"^(\d{1,3}\.){3}\d{1,3}$")


def say(msg=""):
    print(msg, flush=True)


# ---------------------------------------------------------------------------------------------------
# tbapps.conf: [SECTION] lines and KEY=VALUE lines
# ---------------------------------------------------------------------------------------------------
def read_conf(path):
    sections, order, cur = {"ALL": {}}, [], "ALL"
    for n, line in enumerate(open(path), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^\[([A-Za-z][A-Za-z0-9_]*)\]$", line)
        if m:
            cur = m.group(1).upper()
            if cur != "ALL" and cur not in order:
                order.append(cur)
            sections.setdefault(cur, {})
            continue
        m = re.match(r"^([A-Z_][A-Z0-9_]*)\s*=(.*)$", line)
        if not m:
            raise SystemExit(f"tbapps.conf line {n}: '{line}' is not KEY=VALUE or [SECTION]")
        val = m.group(2).strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        sections[cur][m.group(1)] = val
    return sections, order


def clean_host(raw):
    return re.sub(r"^https?://", "", raw.strip().lower()).rstrip("/")


def resolve(env, sections):
    """The settings of one environment: [ALL], then its own section. Returns (errors, warnings, values)."""
    c = dict(sections["ALL"])
    c.update(sections[env])
    errs, warns, v = [], [], {}
    for k, val in c.items():
        if k not in SETTINGS and k not in KEYS:
            warns.append(f"{k} is not a known setting - ignored")
    for k in HOSTS:
        if k in sections["ALL"]:
            errs.append(f"{k} is in [ALL]: each environment has its own names - put it in [{env}] only")
    for k in SETTINGS + KEYS:
        v[k] = c.get(k, "").strip()
    v["ENVIRONMENT"] = env
    v["PROXY"] = (v["PROXY"] or "caddy").lower()
    v["TLS"] = (v["TLS"] or "letsencrypt").lower()
    v["APP_OFFLINE"] = (v["APP_OFFLINE"] or "yes").lower()
    if v["PROXY"] not in ("caddy", "own"):
        errs.append("PROXY must be caddy or own")
    if v["TLS"] not in ("letsencrypt", "internal"):
        errs.append("TLS must be letsencrypt or internal")
    if v["APP_OFFLINE"] not in ("yes", "no"):
        errs.append("APP_OFFLINE must be yes or no")
    # HELP_HOST may stay empty: it is CLOUD_HOST with "help" for "cloud" (staging "helps" for "clouds"). Timebars
    # Cloud sends help.<domain> to cloud.<domain>/help, so the two must share everything after the first label.
    cloud = clean_host(v["CLOUD_HOST"])
    first, _, rest = cloud.partition(".")
    if first not in ("cloud", "clouds") and cloud:
        warns.append(f"CLOUD_HOST {cloud}: Timebars Cloud expects cloud.<domain> (or clouds.<domain>) for its help "
                     "and dashboard names to redirect")
    if not v["HELP_HOST"] and rest:
        v["HELP_HOST"] = ("helps." if first == "clouds" else "help.") + rest
    elif v["HELP_HOST"] and clean_host(v["HELP_HOST"]).partition(".")[2] != rest:
        warns.append(f"HELP_HOST {v['HELP_HOST']} is not on the same domain as CLOUD_HOST ({rest}): its redirect will not reach Cloud")
    hosts = {}
    for k, base, _ in NAMES:
        h = clean_host(v[k])
        if not h:
            errs.append(f"{k} is empty: type this environment's name, e.g. {k}={base}.{env.lower()}.example.com")
            continue
        if not HOST_RE.match(h):
            errs.append(f"{k}: '{h}' is not a hostname like {base}.example.com")
        v[k] = h
        hosts.setdefault(h, []).append(k)
    for h, keys in hosts.items():
        if len(keys) > 1:
            errs.append(f"{h} is used twice ({', '.join(keys)})")
    if v["SERVER_IP"] and not IP_RE.match(v["SERVER_IP"]):
        errs.append(f"SERVER_IP '{v['SERVER_IP']}' is not an IPv4 address like 203.0.113.10")
    if v["LISTEN_IP"] and not IP_RE.match(v["LISTEN_IP"]):
        errs.append(f"LISTEN_IP '{v['LISTEN_IP']}' is not an IPv4 address like 10.0.0.5")
    if v["LISTEN_IP"] and v["PROXY"] == "caddy":
        warns.append("LISTEN_IP is only used with PROXY=own - ignored")
        v["LISTEN_IP"] = ""
    v["LISTEN_IP"] = v["LISTEN_IP"] or "127.0.0.1"
    if not v["SERVER_IP"]:
        warns.append("SERVER_IP is empty: DEPLOY.md shows <server IP> in the DNS records - fill it in later")
    for k in ("EMAIL_FROM", "EMAIL_REPLY_TO", "ACME_EMAIL"):
        if v[k] and not re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", v[k]):
            errs.append(f"{k}: '{v[k]}' is not an email address")
    for e in [e for e in v["HELP_EDITORS"].split(",") if e]:
        if not re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", e):
            errs.append(f"HELP_EDITORS: '{e}' is not an email address (comma separated, no spaces)")
    if v["PROXY"] == "caddy" and v["TLS"] == "letsencrypt" and not v["ACME_EMAIL"]:
        errs.append("ACME_EMAIL is needed for Let's Encrypt (PROXY=caddy, TLS=letsencrypt)")
    if v["OP_URL"] and not v["OP_URL"].startswith("http"):
        errs.append("OP_URL must start with https://")
    for k in SETTINGS + KEYS:
        if re.search(r"\s", v[k]):
            errs.append(f"{k} contains a space")
    return errs, warns, v


